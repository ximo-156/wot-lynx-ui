/** Start B（value 104） */
export const CODE128_START_B = '11010010000'
/** Stop（value 106 + 2 模块终止条，共 13 模块） */
export const CODE128_STOP = '1100011101011'

/** Start B 的 value，也是校验加权和的起点 */
const START_B_VALUE = 104
/** 可打印 ASCII 范围（B 模式数据字符） */
const PRINTABLE_RE = /^[\x20-\x7e]*$/

/**
 * 计算 Code128 校验位：Σ value_i × i（i 从 1 起，Start 占 0 位）mod 103。
 * 入参 values[0] 必须是 Start 的 value（104）。
 */
export function code128Checksum(values: number[]): number {
  let sum = values[0]
  for (let i = 1; i < values.length; i++) {
    sum += values[i] * i
  }
  return sum % 103
}

/**
 * 把可打印 ASCII 文本编码成完整 Code128 B 位流（Start + 数据 + 校验 + Stop）。
 *
 * 非法字符（非 32-126）不静默替换成空格——那会产出「看得见、扫不出」的
 * 假条码；由调用方决定是告警还是整体省略。
 */
export function encodeCode128B(text: string): string {
  if (!PRINTABLE_RE.test(text)) {
    throw new Error('[wd-bar-code] Code128 B supports printable ASCII (32-126) only')
  }
  const values: number[] = [START_B_VALUE]
  for (const ch of text) values.push(ch.charCodeAt(0) - 32)
  values.push(code128Checksum(values))

  let bits = CODE128_START_B
  for (const v of values.slice(1)) {
    const pattern = CODE128_PATTERNS[v]
    if (!pattern) {
      // 越界 value（正常路径不会出现）：告警而非静默回退成空格图案
      console.warn('[wd-bar-code] Code128 校验位越界:', v)
      continue
    }
    bits += pattern
  }
  return bits + CODE128_STOP
}
