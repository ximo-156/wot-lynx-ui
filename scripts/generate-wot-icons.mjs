#!/usr/bin/env node
/** 从离线 wot-ui 2.3.2 图标字体构建原生 text 码点集，保留本地 iconfont 扩展。 */
import { readFileSync, writeFileSync, copyFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ref = resolve(root, '.wot-ref/src-2.3.2/components/wd-icon')
const source = readFileSync(resolve(ref, 'iconfont.scss'), 'utf8')
const unicodes = Object.fromEntries([...source.matchAll(/\.wd-icon-([^:]+):before\s*\{\s*content:\s*"\\([\da-f]+)";/g)].map((m) => [m[1], m[2]]))
if (Object.keys(unicodes).length !== 305) throw new Error('Official 2.3.2 icon map changed or parsing failed')
const output = resolve(root, 'packages/ui/src/icons/sets/wot-icons.ts')
const font = resolve(root, 'packages/ui/src/icons/fonts/wot-icons.ttf')
const css = resolve(root, 'packages/ui/src/icons/fonts/wot-icons.css')
const text = `// AUTO-GENERATED by scripts/generate-wot-icons.mjs — DO NOT EDIT.\n// wot-ui 2.3.2 官方图标（305 个）；保留名字、码点与字体字节。\nimport type { FontIconSet } from '../types'\nexport const wotIconsSet: FontIconSet = {\n  key: 'wot',\n  type: 'font',\n  fontFamily: 'wd-wot-icons',\n  unicodes: ${JSON.stringify(unicodes, null, 2)}\n}\n`
const fontCss = `/* Generated official wot-ui 2.3.2 font. Glyphs render as native text, not ::before. */\n@font-face {\n  font-family: 'wd-wot-icons';\n  src: url('./wot-icons.ttf') format('truetype');\n  font-weight: normal;\n  font-style: normal;\n}\n`
if (process.argv.includes('--check')) {
  for (const [path, expected] of [[output, text], [css, fontCss]]) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== expected) throw new Error(`Generated official font map is stale: ${path}`)
  }
  if (!existsSync(font) || !readFileSync(font).equals(readFileSync(resolve(ref, 'iconfont.ttf')))) throw new Error('Official font bytes differ')
} else {
  writeFileSync(output, text)
  writeFileSync(css, fontCss)
  copyFileSync(resolve(ref, 'iconfont.ttf'), font)
}
console.log(`Official wot-ui 2.3.2 icons: ${Object.keys(unicodes).length}; ${process.argv.includes('--check') ? 'checked' : 'generated'}`)
