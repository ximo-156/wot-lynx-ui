#!/usr/bin/env node
/**
 * build-dist.mjs — 生成 `dist/` 入口桥接层
 *
 * ## 这个脚本不做什么（重要）
 *
 * 它**不编译** `.vue` / `.ts`。本库的组件是 Vue Lynx 单文件组件，要变成可执行
 * 代码需要 Vue SFC 编译器 + Lynx worklet 转换 + SCSS 编译，且产物与宿主平台的
 * 双线程运行时强绑定。把这些塞进一个 `node` 脚本里既不现实、也会让「同一份源码
 * 在 Rspeedy 里能跑、在 dist 里跑不起来」的分裂更严重。
 *
 * ## 它实际做什么
 *
 * 生成**子路径解析垫片**。`wot-lynx-ui/primitives/wd-button` 这个子路径需要
 * 落到一个具体文件上，而组件目录里没有 `index.ts`，所以必须有：
 *
 *   dist/primitives/wd-button/index.mjs
 *     → export { default } from '../../../src/primitives/wd-button/wd-button.vue'
 *
 * 消费方的构建器（Rspeedy / Vite / webpack）顺着这条 re-export 找到源码并编译。
 * 换句话说：**dist 是路径别名，不是编译产物**。
 *
 * 产物结构（每个包各自一份 dist；ADR-023 后包边界见 packages.json）：
 *   dist/
 *   ├── index.mjs / index.d.ts     — 主入口（re-export src/index.ts）
 *   ├── theme/index.css            — 主题 CSS（从 @wot-lynx/core 的产物复制，仅门面）
 *   └── <组件根>/
 *       └── wd-xxx/
 *           ├── index.mjs          — 组件入口桥接
 *           └── index.d.ts         — 类型桥接
 *
 * ## 因此 dist 的能力边界
 *
 *   ✅ 能编译 `.vue` 的打包器（Rspeedy / Vite + @vitejs/plugin-vue / webpack + vue-loader）
 *   ❌ 裸 Node / SSR 直跑（`ERR_UNKNOWN_FILE_EXTENSION: .vue`）
 *
 * 后者需要真正的编译产物，属于 ADR-007 的待办，不是本脚本的职责。
 *
 * ## 为什么必须先清空 dist
 *
 * 组件会在 `src/primitives` 与 `src/components` 之间迁移（2026-10-23 就整体迁过
 * 一次）。不清空的话旧路径的垫片会残留，指向已经不存在的源码 —— 而
 * 「文件存在」类校验照样通过，只有消费方真正 import 时才炸。
 * `scripts/check-exports.mjs --built` 会解析每条 re-export 的目标来兜这个底。
 */

import { readdirSync, readFileSync, mkdirSync, writeFileSync, copyFileSync, existsSync, statSync, rmSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'


const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

/** 包划分来自 packages.json（ADR-023）；每个组件包各自构建 dist 桥接层 */
const MANIFEST = JSON.parse(readFileSync(join(ROOT, 'docs/architecture/packages.json'), 'utf8'))
const COMPONENT_PKGS = MANIFEST.packages.filter((p) => p.componentRoot && existsSync(join(ROOT, p.dir)))
const CORE_SRC = join(ROOT, 'packages/core/src')

function ensureDir(dir) {
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true })
  }
}

/**
 * 两个组件根：L3.5 基础件（primitives）与 L4 业务组件（components）。
 * ⚠️ 新增组件根必须加进来，否则该根的 `exports` 子路径（./primitives/*）没有产物，
 *    非 Rspeedy 消费者会 404（scripts/check-exports.mjs --built 会拦住）。
 */
const COMPONENT_ROOTS = ['primitives', 'components']

/**
 * 组件目录 = 组件根下的**所有子目录**，不按 `wd-` 前缀过滤。
 *
 * 原因：`exports` 的 source 目标是「组件根 + 通配段 + 通配文件名」，通配符
 * 匹配的是「任意目录名」，无法表达「只要 wd- 前缀」。若 dist 侧只产出 `wd-*`，
 * 就会出现 `wot-lynx-ui/components/wot-ui` 在 source 条件可解析、在 import
 * 条件 404 的不一致（`wot-ui` 是对齐上游的占位组件，不在 barrel 里但确实
 * 存在于目录中）。
 *
 * 两侧条目集合必须一致，`check-exports.mjs --built` 的 5b 节会强制这一点。
 */
function getComponentDirs(srcDir) {
  if (!existsSync(srcDir)) return []
  return readdirSync(srcDir)
    .filter((name) => statSync(join(srcDir, name)).isDirectory())
    .sort()
}

/** 单个包的 dist 构建上下文 */
function pkgContext(pkg) {
  const pkgDir = join(ROOT, pkg.dir)
  const srcDir = join(pkgDir, pkg.componentRoot)
  const distDir = join(pkgDir, 'dist')
  // dist 侧的组件子目录：src → ''，src/components → 'components'（与 exports 对齐）
  const distSub = relative('src', pkg.componentRoot)
  // 从 dist/<sub>/<comp>/ 回退到包根的层数
  const up = distSub ? '../../../..' : '../../..'
  return { pkg, pkgDir, srcDir, distDir, distSub, up }
}

function buildMainEntry(ctx) {
  const lines = [
    '// Auto-generated by build-dist.mjs — do not edit',
    "export * from '../src/index.ts'",
    "export { default } from '../src/index.ts'",
    ''
  ]
  ensureDir(ctx.distDir)
  writeFileSync(join(ctx.distDir, 'index.mjs'), lines.join('\n'))
  console.log(`  ${pkgName(ctx.pkg)} dist/index.mjs (complete public API)`)
}

const pkgName = (pkg) => pkg.name

function buildComponentEntries(ctx) {
  let total = 0
  const components = getComponentDirs(ctx.srcDir)
  if (components.length === 0) return 0
  const distRootDir = ctx.distSub ? join(ctx.distDir, ctx.distSub) : ctx.distDir

  for (const comp of components) {
    const compDistDir = join(distRootDir, comp)
    ensureDir(compDistDir)

    const source = `${ctx.up}/src/${ctx.distSub ? `${ctx.distSub}/` : ''}${comp}`
    const entryExports = existsSync(join(ctx.srcDir, comp, 'index.ts'))
      ? `export * from '${source}/index.ts'\n`
      : ''
    writeFileSync(
      join(compDistDir, 'index.mjs'),
      `// Auto-generated by build-dist.mjs\n${entryExports}export { default } from '${source}/${comp}.vue'\n`
    )

    const typeExports = existsSync(join(ctx.srcDir, comp, 'types.ts'))
      ? `export * from '${source}/types'\n`
      : ''
    writeFileSync(
      join(compDistDir, 'index.d.ts'),
      `// Auto-generated by build-dist.mjs\n${entryExports}export { default } from '${source}/${comp}.vue'\n${typeExports}`
    )
  }

  console.log(`  ${ctx.pkg.name} dist/${ctx.distSub ? `${ctx.distSub}/` : ''}(${components.length} components)`)
  return components.length
}

/** 主题入口：@wot-lynx/core 的编译产物复制到门面 dist（source 条件由门面 scss 转发） */
function buildTheme(ctx) {
  if (ctx.pkg.role !== 'umbrella') return
  const themeDistDir = join(ctx.distDir, 'theme')

  const themeSrc = join(CORE_SRC, 'styles/theme/index.css')
  if (existsSync(themeSrc)) {
    ensureDir(themeDistDir)
    copyFileSync(themeSrc, join(themeDistDir, 'index.css'))
    console.log('  wot-lynx-ui dist/theme/index.css')
  }

  const presetsSrc = join(CORE_SRC, 'styles/theme/presets')
  if (existsSync(presetsSrc)) {
    const cssFiles = readdirSync(presetsSrc).filter((n) => n.endsWith('.css'))
    if (cssFiles.length > 0) {
      const presetsDist = join(themeDistDir, 'presets')
      ensureDir(presetsDist)
      for (const file of cssFiles) {
        copyFileSync(join(presetsSrc, file), join(presetsDist, file))
      }
      console.log(`  wot-lynx-ui dist/theme/presets/ (${cssFiles.length} files)`)
    }
  }
}

function buildTypes(ctx) {
  writeFileSync(
    join(ctx.distDir, 'index.d.ts'),
    `// Auto-generated by build-dist.mjs\nexport * from '../src/index.ts'\nexport { default } from '../src/index.ts'\n`
  )
  console.log(`  ${ctx.pkg.name} dist/index.d.ts`)
}

console.log('Building dist...')
let totalComponents = 0
for (const pkg of COMPONENT_PKGS) {
  const ctx = pkgContext(pkg)
  // 先清空：组件迁移后旧垫片必须消失，否则会留下指向不存在源码的「僵尸入口」
  // （见文件头说明）。
  //
  // maxRetries/retryDelay 是给 Windows 用的：`rmSync` 在目录里还有未释放的句柄时
  // 抛 EPERM/EBUSY，而 `force: true` 只忽略 ENOENT。没有重试的话，紧跟在
  // `pnpm test` / `build:demo` 之后的构建会随机失败（2026-10-23 实际遇到一次）。
  if (existsSync(ctx.distDir)) {
    rmSync(ctx.distDir, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 })
  }
  ensureDir(ctx.distDir)
  buildMainEntry(ctx)
  totalComponents += buildComponentEntries(ctx)
  buildTheme(ctx)
  buildTypes(ctx)
}
console.log(`Done. ${COMPONENT_PKGS.length} packages / ${totalComponents} components.`)
