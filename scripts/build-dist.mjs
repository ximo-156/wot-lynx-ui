#!/usr/bin/env node
/**
 * build-dist.mjs — 生成预构建产物（dist/）
 *
 * 将 TypeScript 源码编译为 ESM + .d.ts，供非 Rspeedy 消费者使用。
 * 源码分发（source 条件导出）保持不变，dist 作为兜底。
 *
 * 产物结构：
 *   dist/
 *   ├── index.mjs          — 主入口（re-export 所有组件）
 *   ├── index.d.ts         — 类型声明
 *   ├── theme/index.css    — 主题 CSS（从 src/styles/theme/index.css 复制）
 *   └── components/
 *       └── wd-xxx/
 *           ├── index.mjs  — 组件 ESM
 *           └── index.d.ts — 组件类型声明
 *
 * 注意：组件 .vue 文件无法直接编译为 .mjs（需要 Vue 编译器），
 * 因此 dist/components/<组件名>/index.mjs 是 re-export 源码的桥接文件，
 * 由消费方的构建器（Rspeedy/Vite/webpack）处理 .vue 编译。
 */

import { readdirSync, mkdirSync, writeFileSync, copyFileSync, existsSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const UI_DIR = join(ROOT, 'packages/ui')
const SRC_DIR = join(UI_DIR, 'src')
const DIST_DIR = join(UI_DIR, 'dist')

function ensureDir(dir) {
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true })
  }
}

function getComponentDirs() {
  const componentsDir = join(SRC_DIR, 'components')
  return readdirSync(componentsDir)
    .filter((name) => name.startsWith('wd-'))
    .filter((name) => statSync(join(componentsDir, name)).isDirectory())
    .sort()
}

function buildMainEntry() {
  const components = getComponentDirs()
  const lines = [
    '// Auto-generated by build-dist.mjs — do not edit',
    ''
  ]

  for (const comp of components) {
    const pascalName = comp
      .split('-')
      .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
      .join('')
    lines.push(`export { default as ${pascalName} } from '../src/components/${comp}/${comp}.vue'`)
  }

  lines.push('')
  lines.push("export { default } from '../src/index.ts'")
  lines.push('')

  ensureDir(DIST_DIR)
  writeFileSync(join(DIST_DIR, 'index.mjs'), lines.join('\n'))
  console.log(`  dist/index.mjs (${components.length} components)`)
}

function buildComponentEntries() {
  const components = getComponentDirs()
  const distComponentsDir = join(DIST_DIR, 'components')

  for (const comp of components) {
    const compDistDir = join(distComponentsDir, comp)
    ensureDir(compDistDir)

    const pascalName = comp
      .split('-')
      .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
      .join('')

    // index.mjs — re-export 源码
    writeFileSync(
      join(compDistDir, 'index.mjs'),
      `// Auto-generated by build-dist.mjs\nexport { default } from '../../../src/components/${comp}/${comp}.vue'\n`
    )

    // index.d.ts — re-export 类型
    writeFileSync(
      join(compDistDir, 'index.d.ts'),
      `// Auto-generated by build-dist.mjs\nexport { default } from '../../../src/components/${comp}/${comp}.vue'\nexport type { ${pascalName}Props } from '../../../src/components/${comp}/types'\n`
    )
  }

  console.log(`  dist/components/ (${components.length} components)`)
}

function buildTheme() {
  const themeSrc = join(SRC_DIR, 'styles/theme/index.css')
  const themeDistDir = join(DIST_DIR, 'theme')

  if (existsSync(themeSrc)) {
    ensureDir(themeDistDir)
    copyFileSync(themeSrc, join(themeDistDir, 'index.css'))
    console.log('  dist/theme/index.css')
  }
}

function buildTypes() {
  // 主类型声明 — re-export 源码类型
  writeFileSync(
    join(DIST_DIR, 'index.d.ts'),
    `// Auto-generated by build-dist.mjs\nexport * from '../src/index.ts'\n`
  )
  console.log('  dist/index.d.ts')
}

console.log('Building dist...')
ensureDir(DIST_DIR)
buildMainEntry()
buildComponentEntries()
buildTheme()
buildTypes()
console.log('Done.')
