#!/usr/bin/env node
/**
 * 把 iconfont.cn 导出的 symbol 模式产物转换为组件库内置「字体图标集」。
 *
 * 产物两件套：
 * 1. TS 图标集模块（默认 packages/ui/src/icons/sets/<key>.ts）：图标名 ->
 *    unicode 码点映射，经 src/icons/registry.ts 注册后由 wd-icon 渲染；
 * 2. 字体文件（默认 packages/ui/src/icons/fonts/<key>.ttf）：从导出目录拷贝，
 *    配合 src/icons/fonts/<key>.css 的 @font-face 声明使用。
 *
 * Lynx 注意事项：Lynx CSS 不支持 ::before/::after，经典 iconfont 的
 * `content` 写法不可用，wd-icon 的字体模式把码点字形直接作为 <text> 子节点
 * 渲染（见 wd-icon.vue 与 src/icons/fonts/*.css）。
 *
 * 码点来源：iconfont.json 的 glyphs[].unicode（symbol 的 path 数据本方案不用，
 * 渲染完全由字体文件负责）。
 *
 * 用法：
 *   node scripts/generate-iconfont.mjs <iconfont.js | 其所在目录> [输出.ts] [--key <集合键>] [--check]
 *
 * 示例（扩展一套新字体图标）：
 *   node scripts/generate-iconfont.mjs /tmp/iconfont2 packages/ui/src/icons/sets/mdi.ts --key mdi
 *   （随后在 registry.ts 注册生成的集合，并补充 fonts/mdi.css 的 @font-face）
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/** 字体族名约定：wd-<集合键>（与 fonts/<key>.css 的 @font-face 一致） */
const fontFamilyOf = (key) => `wd-${key}`

function fail(msg) {
  console.error(`[generate-iconfont] ${msg}`)
  process.exit(1)
}

function statIsDir(p) {
  try {
    return statSync(p).isDirectory()
  } catch {
    return false
  }
}

/** 解析全部 <symbol id>，拿到图标名清单（顺序即导出顺序） */
function parseSymbolNames(js) {
  const symbolRe = /<symbol\b([^>]*)>/g
  const attrRe = /([\w-]+)\s*=\s*"([^"]*)"/g
  const names = []
  let match
  while ((match = symbolRe.exec(js)) !== null) {
    const attrs = {}
    let attrMatch
    attrRe.lastIndex = 0
    while ((attrMatch = attrRe.exec(match[1])) !== null) {
      attrs[attrMatch[1]] = attrMatch[2]
    }
    const id = attrs.id || ''
    if (!id) continue
    names.push(id.startsWith('icon-') ? id.slice(5) : id)
  }
  return names
}

/**
 * 交叉校验并产出 name -> unicode 映射。
 * symbol 决定图标清单与顺序，iconfont.json 的 glyphs[].unicode 提供码点。
 */
function buildUnicodeMap(dir, names) {
  const jsonPath = path.join(dir, 'iconfont.json')
  if (!existsSync(jsonPath)) fail(`未找到 iconfont.json（码点来源）：${jsonPath}`)
  let glyphs
  try {
    glyphs = JSON.parse(readFileSync(jsonPath, 'utf8')).glyphs || []
  } catch (e) {
    fail(`iconfont.json 解析失败：${e.message}`)
  }
  const byName = new Map(glyphs.map((g) => [g.font_class, g.unicode]))
  const missing = names.filter((n) => !byName.has(n))
  if (missing.length) fail(`以下图标在 iconfont.json 中找不到码点：${missing.join(', ')}`)

  const unicodes = {}
  const seenUnicode = new Map()
  for (const name of names) {
    const unicode = byName.get(name)
    if (seenUnicode.has(unicode)) {
      fail(`码点重复：${name} 与 ${seenUnicode.get(unicode)} 同为 ${unicode}`)
    }
    seenUnicode.set(unicode, name)
    unicodes[name] = unicode
  }
  return unicodes
}

function render(key, unicodes) {
  const lines = [
    '// AUTO-GENERATED by scripts/generate-iconfont.mjs — DO NOT EDIT.',
    `// 字体图标集「${key}」：${Object.keys(unicodes).length} 个图标，码点来自 iconfont.json。`,
    '// 重新生成：node scripts/generate-iconfont.mjs <iconfont.js 或所在目录> <本文件路径>',
    `// 字体文件：src/icons/fonts/${key}.ttf（@font-face 见同目录 ${key}.css，族名 ${fontFamilyOf(key)}）`,
    "import type { FontIconSet } from '../types'",
    '',
    `export const ${key.replace(/[^\w]/g, '_')}Set: FontIconSet = {`,
    `  key: '${key}',`,
    "  type: 'font',",
    `  fontFamily: '${fontFamilyOf(key)}',`,
    '  unicodes: {'
  ]
  for (const [name, unicode] of Object.entries(unicodes)) {
    lines.push(`    '${name}': '${unicode}',`)
  }
  lines.push('  }', '}', '')
  return lines.join('\n')
}

function main() {
  const args = process.argv.slice(2)
  let input, output, key
  const rest = []
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--key') key = args[++i]
    else if (args[i] === '--check') rest.push('--check')
    else rest.push(args[i])
  }
  const check = rest.includes('--check')
  ;[input, output] = rest.filter((a) => a !== '--check')

  if (!input) fail('缺少输入：<iconfont.js 或其所在目录>')
  if (!existsSync(input)) fail(`输入不存在：${input}`)

  const dir = statIsDir(input) ? input : path.dirname(input)
  const jsPath = statIsDir(input) ? path.join(input, 'iconfont.js') : input
  if (!existsSync(jsPath)) fail(`未找到 iconfont.js：${jsPath}`)

  output = output || path.join(root, 'packages/ui/src/icons/sets/iconfont.ts')
  key = key || path.basename(output).replace(/\.ts$/, '')

  const names = parseSymbolNames(readFileSync(jsPath, 'utf8'))
  if (names.length === 0) fail('未解析到任何 symbol（需要 iconfont.cn 的 symbol 模式产物）')
  const dup = names.filter((n, i) => names.indexOf(n) !== i)
  if (dup.length) fail(`图标名重复：${[...new Set(dup)].join(', ')}`)

  const unicodes = buildUnicodeMap(dir, names)
  const content = render(key, unicodes)

  // 字体文件随产物一起落位（拷贝而非生成，保证与导出物字节一致）
  const fontSrc = path.join(dir, 'iconfont.ttf')
  if (!existsSync(fontSrc)) fail(`未找到字体文件：${fontSrc}`)
  const fontDst = path.join(root, 'packages/ui/src/icons/fonts', `${key}.ttf`)

  if (check) {
    if (!existsSync(output) || readFileSync(output, 'utf8') !== content) {
      fail(`输出已过期：${output}（重新运行生成脚本）`)
    }
    if (!existsSync(fontDst)) fail(`字体文件缺失：${fontDst}（重新运行生成脚本）`)
    const src = readFileSync(fontSrc)
    const dst = readFileSync(fontDst)
    if (!src.equals(dst)) fail(`字体文件已过期：${fontDst}（重新运行生成脚本）`)
    console.log(`[generate-iconfont] ${output} 与 ${path.relative(root, fontDst)} 已是最新（${names.length} 个图标）`)
    return
  }

  writeFileSync(output, content)
  mkdirSync(path.dirname(fontDst), { recursive: true })
  copyFileSync(fontSrc, fontDst)
  console.log(`[generate-iconfont] 已生成 ${output}（${names.length} 个图标，key=${key}）`)
  console.log(`[generate-iconfont] 已拷贝字体 ${path.relative(root, fontDst)}（族名 ${fontFamilyOf(key)}）`)
}

main()
